ALTER TABLE estudios ADD COLUMN encerrado_em TIMESTAMP(6) WITH TIME ZONE;

CREATE TABLE expurgos_estudio (
    estudio_id BIGINT PRIMARY KEY REFERENCES estudios(id),
    solicitado_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    lista_espera_ate TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    operacional_ate TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    lista_espera_concluido_em TIMESTAMP(6) WITH TIME ZONE,
    operacional_concluido_em TIMESTAMP(6) WITH TIME ZONE,
    recebimentos_arquivo_concluido_em TIMESTAMP(6) WITH TIME ZONE,
    tentativas INTEGER NOT NULL DEFAULT 0 CHECK (tentativas >= 0),
    proxima_tentativa_em TIMESTAMP(6) WITH TIME ZONE,
    ultimo_erro VARCHAR(60)
);

CREATE INDEX idx_expurgos_estudio_prontos
    ON expurgos_estudio(proxima_tentativa_em, lista_espera_ate, operacional_ate, recebimentos_arquivo_concluido_em);

-- Financial snapshot contains no FK or identifying data for a client, reservation, or user.
-- The source ID is an internal idempotency reference only; each receipt has its own calendar-year deadline.
CREATE TABLE recebimentos_arquivo (
    recebimento_origem_id BIGINT PRIMARY KEY,
    estudio_id BIGINT NOT NULL REFERENCES estudios(id),
    valor NUMERIC(12,2) NOT NULL CHECK (valor >= 0),
    confirmado_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    moeda CHAR(3) NOT NULL DEFAULT 'BRL' CHECK (moeda = 'BRL'),
    arquivado_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ano_calendario SMALLINT NOT NULL CHECK (ano_calendario BETWEEN 1900 AND 9993),
    expira_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_recebimentos_arquivo_estudio_origem UNIQUE (estudio_id, recebimento_origem_id)
);

CREATE INDEX idx_recebimentos_arquivo_estudio_data
    ON recebimentos_arquivo(estudio_id, confirmado_em);

CREATE INDEX idx_recebimentos_arquivo_expira
    ON recebimentos_arquivo(estudio_id, expira_em);

-- The source receipt ID intentionally has no FK: a hold can be registered while the source
-- receipt still points to booking/client/user, before it is moved to the minimized archive.
-- The study FK keeps the record tenant-scoped. An active hold is never auto-released at review time.
CREATE TABLE retencoes_legais_financeiras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudio_id BIGINT NOT NULL REFERENCES estudios(id),
    recebimento_origem_id BIGINT NOT NULL,
    tipo VARCHAR(32) NOT NULL CHECK (tipo IN ('OBRIGACAO_ESPECIFICA', 'PROCESSO_PENDENTE', 'FISCALIZACAO_PENDENTE')),
    justificativa VARCHAR(1000) NOT NULL CHECK (LENGTH(TRIM(justificativa)) > 0),
    escopo VARCHAR(1000) NOT NULL CHECK (LENGTH(TRIM(escopo)) > 0),
    iniciada_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revisar_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revisada_em TIMESTAMP(6) WITH TIME ZONE,
    encerrada_em TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ck_retencao_financeira_revisao CHECK (revisar_em > iniciada_em),
    CONSTRAINT ck_retencao_financeira_revisada CHECK (revisada_em IS NULL OR revisada_em >= iniciada_em),
    CONSTRAINT ck_retencao_financeira_encerramento CHECK (encerrada_em IS NULL OR encerrada_em >= iniciada_em)
);

CREATE INDEX idx_retencoes_legais_financeiras_ativas
    ON retencoes_legais_financeiras(estudio_id, recebimento_origem_id, encerrada_em, revisar_em);
