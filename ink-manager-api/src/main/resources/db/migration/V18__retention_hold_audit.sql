ALTER TABLE retencoes_legais_financeiras
    ADD CONSTRAINT uq_retencoes_legais_estudio_id UNIQUE (estudio_id, id);

CREATE TABLE retencoes_legais_financeiras_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudio_id BIGINT NOT NULL REFERENCES estudios(id),
    retencao_id BIGINT NOT NULL,
    ator_usuario_id BIGINT NOT NULL,
    acao VARCHAR(16) NOT NULL CHECK (acao IN ('CRIADO', 'REVISADO', 'ENCERRADO')),
    ocorrido_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    nota VARCHAR(1000),
    CONSTRAINT fk_retencao_evento_hold
        FOREIGN KEY (estudio_id, retencao_id)
        REFERENCES retencoes_legais_financeiras(estudio_id, id)
        ON DELETE CASCADE
);

CREATE INDEX idx_retencao_eventos_hold
    ON retencoes_legais_financeiras_eventos(estudio_id, retencao_id, ocorrido_em);
