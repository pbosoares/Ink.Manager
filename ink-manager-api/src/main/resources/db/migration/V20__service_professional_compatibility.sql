CREATE TABLE servicos_profissionais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudio_id BIGINT NOT NULL REFERENCES estudios(id),
    servico_id BIGINT NOT NULL,
    profissional_id BIGINT NOT NULL,
    CONSTRAINT uq_servicos_profissionais_vinculo UNIQUE (estudio_id, servico_id, profissional_id),
    CONSTRAINT fk_servicos_profissionais_servico_estudio
        FOREIGN KEY (servico_id, estudio_id) REFERENCES servicos(id, estudio_id),
    CONSTRAINT fk_servicos_profissionais_profissional_estudio
        FOREIGN KEY (profissional_id, estudio_id) REFERENCES profissionais(id, estudio_id)
);

CREATE INDEX idx_servicos_profissionais_profissional
    ON servicos_profissionais(estudio_id, profissional_id, servico_id);

-- Preserve the legacy behavior: every existing service was available to every
-- professional in the same studio. No historical appointment is rewritten.
INSERT INTO servicos_profissionais (estudio_id, servico_id, profissional_id)
SELECT s.estudio_id, s.id, p.id
FROM servicos s
JOIN profissionais p ON p.estudio_id = s.estudio_id;
