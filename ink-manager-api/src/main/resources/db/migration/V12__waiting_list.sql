CREATE TABLE lista_espera (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudio_id BIGINT NOT NULL REFERENCES estudios(id),
    servico_id BIGINT NOT NULL,
    profissional_id BIGINT,
    inicio_desejado TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    fim_desejado TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    telefone VARCHAR(30) NOT NULL,
    chave_idempotencia UUID NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('AGUARDANDO','OFERTADA','RESERVADA','CANCELADA','EXPIRADA')),
    criado_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_lista_servico_tenant FOREIGN KEY (servico_id, estudio_id) REFERENCES servicos(id, estudio_id),
    CONSTRAINT fk_lista_profissional_tenant FOREIGN KEY (profissional_id, estudio_id) REFERENCES profissionais(id, estudio_id),
    CONSTRAINT uq_lista_idempotencia UNIQUE (estudio_id, chave_idempotencia),
    CONSTRAINT uq_lista_id_tenant UNIQUE (id, estudio_id),
    CONSTRAINT ck_lista_janela CHECK (fim_desejado > inicio_desejado)
);
CREATE INDEX idx_lista_match ON lista_espera(estudio_id, servico_id, estado, criado_em);

CREATE TABLE ofertas_lista_espera (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudio_id BIGINT NOT NULL REFERENCES estudios(id),
    lista_espera_id BIGINT NOT NULL,
    marcacao_cancelada_id BIGINT NOT NULL,
    reserva_id BIGINT,
    data DATE NOT NULL,
    horario TIME(6) NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('AGUARDANDO_ENVIO','OFERTADA','ACEITA','RECUSADA','EXPIRADA','INVALIDADA')),
    token_hash VARCHAR(64),
    token_prazo TIMESTAMP(6) WITH TIME ZONE,
    criado_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_oferta_lista_tenant FOREIGN KEY (lista_espera_id, estudio_id) REFERENCES lista_espera(id, estudio_id),
    CONSTRAINT fk_oferta_cancelada_tenant FOREIGN KEY (marcacao_cancelada_id, estudio_id) REFERENCES marcacoes(id, estudio_id),
    CONSTRAINT fk_oferta_reserva_tenant FOREIGN KEY (reserva_id, estudio_id) REFERENCES marcacoes(id, estudio_id),
    CONSTRAINT uq_oferta_id_tenant UNIQUE (id, estudio_id),
    CONSTRAINT uq_oferta_reserva UNIQUE (reserva_id),
    CONSTRAINT uq_oferta_token UNIQUE (estudio_id, token_hash)
);
CREATE INDEX idx_oferta_ativa_slot ON ofertas_lista_espera(estudio_id, marcacao_cancelada_id, estado);
