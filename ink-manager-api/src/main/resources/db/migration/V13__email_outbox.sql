CREATE TABLE email_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudio_id BIGINT NOT NULL REFERENCES estudios(id),
    destinatario VARCHAR(254) NOT NULL,
    tipo VARCHAR(80) NOT NULL,
    chave_idempotencia VARCHAR(180) NOT NULL,
    disponivel_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    referencia VARCHAR(255) NOT NULL,
    dados_json VARCHAR(8000) NOT NULL,
    estado VARCHAR(16) NOT NULL DEFAULT 'PENDENTE'
        CHECK (estado IN ('PENDENTE','ENVIANDO','ENVIADO','FALHOU','INVALIDADO')),
    tentativas INTEGER NOT NULL DEFAULT 0 CHECK (tentativas >= 0),
    lease_ate TIMESTAMP(6) WITH TIME ZONE,
    lease_token VARCHAR(36),
    criado_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    enviado_em TIMESTAMP(6) WITH TIME ZONE,
    ultimo_erro VARCHAR(80),
    CONSTRAINT uq_email_outbox_estudio_chave UNIQUE (estudio_id, chave_idempotencia),
    CONSTRAINT ck_email_outbox_lease CHECK (
        (estado = 'ENVIANDO' AND lease_ate IS NOT NULL AND lease_token IS NOT NULL)
        OR (estado <> 'ENVIANDO' AND lease_ate IS NULL AND lease_token IS NULL)
    )
);

CREATE INDEX idx_email_outbox_pronto ON email_outbox(estado, disponivel_em, id);
CREATE INDEX idx_email_outbox_estudio ON email_outbox(estudio_id, criado_em);
